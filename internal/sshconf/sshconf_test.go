const sample = `Include /Users/me/.colima/ssh_config

Host *
	IdentityAgent "~/Library/Group Containers/2BUA8C4S2C.com.1password/t/agent.sock"

# the school box
Host epitech
        HostName 203.0.113.5
        User ubuntu
        SetEnv TERM=xterm-256color

Host pve
	HostName 10.0.0.100
	User root
	SetEnv TERM=xterm-256color

Host starrs
	HostName 10.5.0.100
	User ops
`

func TestRoundTrip(t *testing.T) {
	f := Parse("x", sample)
	if got := f.Content(); got != sample {
		t.Fatalf("round trip changed the file:\n%s", got)
	}
	hosts := f.Hosts()
	if len(hosts) != 4 {
		t.Fatalf("want 4 host blocks, got %d", len(hosts))
	}
	if !hosts[0].IsWildcard() || hosts[1].Alias() != "epitech" {
		t.Fatalf("aliases wrong: %v", hosts)
	}
	if hosts[1].HeaderComment() != "the school box" {
		t.Fatalf("header comment: %q", hosts[1].HeaderComment())
	}
	if v, _ := hosts[2].Get("hostname"); v != "10.0.0.100" {
		t.Fatalf("Get is case-insensitive on keys: %q", v)
	}
}

func TestSetKeepsIndentAndSpelling(t *testing.T) {
	f := Parse("x", sample)
	pve := f.Hosts()[2]
	pve.Set("hostname", "10.0.0.200")
	pve.Set("Port", "2222")
	if !strings.Contains(f.Content(), "\tHostName 10.0.0.200\n") {
		t.Fatalf("value not replaced in place:\n%s", f.Content())
	}
	if !strings.Contains(f.Content(), "\tSetEnv TERM=xterm-256color\n\tPort 2222\n\nHost starrs") {
		t.Fatalf("new directive not appended with the stanza's indent:\n%s", f.Content())
	}
	epi := f.Hosts()[1]
	epi.Set("Port", "22")
	if !strings.Contains(f.Content(), "        SetEnv TERM=xterm-256color\n        Port 22\n") {
		t.Fatalf("space-indented stanza should stay space-indented:\n%s", f.Content())
	}
}

func TestRemoveAndDelete(t *testing.T) {
	f := Parse("x", sample)
	pve := f.Hosts()[2]
	pve.Remove("SetEnv", func(v string) bool { return strings.HasPrefix(v, "TERM=") })
	if strings.Contains(f.Content(), "Host pve\n\tHostName 10.0.0.100\n\tUser root\n\tSetEnv") {
		t.Fatalf("SetEnv not removed:\n%s", f.Content())
	}
	f.DeleteBlock(f.Hosts()[1])
	want := "agent.sock\"\n\nHost pve\n"
	if !strings.Contains(f.Content(), want) || strings.Contains(f.Content(), "epitech") {
		t.Fatalf("delete left debris:\n%s", f.Content())
	}
	if len(f.Hosts()) != 3 {
		t.Fatalf("want 3 blocks after delete, got %d", len(f.Hosts()))
	}
}

func TestAddHostRenameTags(t *testing.T) {
	f := Parse("x", sample)
	b := f.AddHost("omni")
	b.Set("HostName", "203.0.113.23")
	b.Set("User", "ubuntu")
	b.SetTags([]string{"oracle", "prod"})
	if !strings.HasSuffix(f.Content(), "\tUser ops\n\nHost omni\n\t# tags: oracle, prod\n\tHostName 203.0.113.23\n\tUser ubuntu\n") {
		t.Fatalf("add host:\n%s", f.Content())
	}
	if got := b.Tags(); len(got) != 2 || got[1] != "prod" {
		t.Fatalf("tags: %v", got)
	}
	b.Rename("oracle-omni")
	if b.Alias() != "oracle-omni" || !strings.Contains(f.Content(), "\nHost oracle-omni\n") {
		t.Fatalf("rename:\n%s", f.Content())
	}
	b.SetTags(nil)
	if strings.Contains(f.Content(), "tags:") {
		t.Fatalf("tags not removed")
	}
}

func TestFileHeaderIsNotAHostComment(t *testing.T) {
	f := Parse("x", "# generated by lima\n# do not edit\nHost colima\n\tUser me\n")
	if c := f.Hosts()[0].HeaderComment(); c != "" {
		t.Fatalf("file header taken as host comment: %q", c)
	}
	f = Parse("x", "Host a\n\n# the b box\nHost b\n")
	if c := f.Hosts()[1].HeaderComment(); c != "the b box" {
		t.Fatalf("host comment lost: %q", c)
	}
}

func TestIncludeCycleAndSymlinkSave(t *testing.T) {
	dir := t.TempDir()
	a, b := filepath.Join(dir, "a"), filepath.Join(dir, "b")
	os.WriteFile(a, []byte("Include "+b+"\nHost one\n"), 0o600)
	os.WriteFile(b, []byte("Include "+a+"\nHost two\n"), 0o600)
	f, err := Load(a)
	if err != nil {
		t.Fatal(err)
	}
	if n := len(f.Hosts()); n != 2 {
		t.Fatalf("a<->b include cycle should yield 2 hosts, got %d", n)
	}

	real := filepath.Join(dir, "dotfiles-config")
	link := filepath.Join(dir, "config")
	os.WriteFile(real, []byte("Host x\n"), 0o600)
	os.Symlink(real, link)
	f, _ = Load(link)
	f.AddHost("y")
	if err := f.Save(); err != nil {
		t.Fatal(err)
	}
	if fi, err := os.Lstat(link); err != nil || fi.Mode()&os.ModeSymlink == 0 {
		t.Fatal("saving through a symlink must keep the symlink")
	}
	if data, _ := os.ReadFile(real); !strings.Contains(string(data), "Host y") {
		t.Fatal("the symlink target should hold the new stanza")
	}

	// Somebody else edits between load and save: refuse rather than clobber.
	f, _ = Load(real)
	time.Sleep(20 * time.Millisecond)
	os.WriteFile(real, []byte("Host x\n\nHost z\n"), 0o600)
	f.AddHost("w")
	if err := f.Save(); !errors.Is(err, ErrChanged) {
		t.Fatalf("want ErrChanged, got %v", err)
	}
}

